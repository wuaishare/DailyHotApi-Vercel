#!/usr/bin/env node
// GitHub-hosted snapshot capture. Writes only verified PUBLIC data to a
// temporary directory. The scheduled workflow uploads accepted files to a
// GitHub Release: no commits, Vercel deployments, or new credentials per tick.
import {mkdir, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {
  SOURCE_VARIANTS, UPSTREAM, validPublicPayload, validSnapshot, parseBoundedJson,
} from '../lib/standby-core.js';

export const MAX_SOURCE_AGE_MS = 3 * 60 * 60 * 1000;
const timeoutMs = 14000;
export async function captureSource(source, {
  fetchImpl = globalThis.fetch, now = () => Date.now(),
} = {}) {
  const variant = SOURCE_VARIANTS[source];
  if (!variant) throw new Error('source_not_approved');
  const url = new URL(UPSTREAM + '/' + source);
  url.searchParams.set('type', variant);
  const response = await fetchImpl(url.toString(), {
    headers:{Accept:'application/json','User-Agent':'hotapi-cloud-snapshot-refresh/1.0'},
    redirect:'error', signal:AbortSignal.timeout(timeoutMs),
  });
  if (response.status !== 200) throw new Error('upstream_http_' + response.status);
  if (!(response.headers.get('content-type') || '').includes('json')) {
    throw new Error('upstream_not_json_200');
  }
  // Share the same byte ceiling as the live Vercel fallback, including
  // chunked responses without Content-Length. Reject before full buffering.
  const data = await parseBoundedJson(response);
  if (!data) throw new Error('upstream_invalid_or_oversized_json');
  if (!validPublicPayload(source, data)) throw new Error('invalid_public_ranking');
  const capturedAt = new Date(now()).toISOString();
  // A just-served cached document is not proof of a fresh scrape. Refuse
  // snapshots with absent, implausible or stale upstream updateTime.
  const updated = Date.parse(data.updateTime);
  if (!Number.isFinite(updated) || now() - updated > MAX_SOURCE_AGE_MS ||
      updated > now() + 120000) throw new Error('upstream_data_not_fresh');
  const result = {
    schema:'hotapi-cloud-snapshot-v1', source, variant, capturedAt,
    payload:data,
  };
  if (!validSnapshot(result, source, variant, now())) {
    throw new Error('generated_snapshot_invalid');
  }
  return result;
}

// A single bounded retry handles temporary remote failures; never repeat
// explicit denial or rate-limit statuses, malformed public data or 200 HTML.
export const retryableCaptureError = (error) => {
  const message = String(error?.message || '');
  return /^upstream_http_5[0-9][0-9]$/.test(message) ||
    error?.name === 'TimeoutError' ||
    (error?.name === 'TypeError' && /fetch failed|network|socket|ECONNRESET|ETIMEDOUT/i.test(message));
};
export async function captureAll({
  outDir, seedFile = null, fetchImpl = globalThis.fetch,
  now = () => Date.now(),
  sleepImpl = (ms) => new Promise(resolve => setTimeout(resolve, ms)),
} = {}) {
  if (typeof outDir !== 'string' || !outDir) throw new Error('out-dir-required');
  await mkdir(outDir, {recursive:true, mode:0o700});
  const ready = {};
  const failed = [];
  // Deliberately bounded to 2 concurrent public requests; avoid overloading bt1.
  const entries = Object.entries(SOURCE_VARIANTS);
  for (let start = 0; start < entries.length; start += 2) {
    await Promise.all(entries.slice(start, start + 2).map(async ([source, variant]) => {
      try {
        let snapshot;
        for (let attempt = 0; attempt < 2; attempt++) {
          try {
            snapshot = await captureSource(source, {fetchImpl, now});
            break;
          } catch (error) {
            if (attempt !== 0 || !retryableCaptureError(error)) throw error;
            console.warn('SNAPSHOT_RETRY ' + source + ' ' +
              String(error?.message || error).slice(0,100));
            await sleepImpl(750);
          }
        }
        const name = source + '-' + variant + '.json';
        await writeFile(resolve(outDir, name), JSON.stringify(snapshot) + '\n',
          {encoding:'utf8', mode:0o600});
        ready[name] = snapshot;
        console.log('SNAPSHOT_OK ' + source + ' rows=' + snapshot.payload.data.length);
      } catch (error) {
        const reason = String(error?.message || error).slice(0,100);
        failed.push(source);
        console.warn('SNAPSHOT_SKIPPED ' + source + ' ' + reason);
      }
    }));
  }
  const expected = entries.length;
  if (seedFile) {
    if (Object.keys(ready).length !== expected) {
      throw new Error('Refuse to write an incomplete bundled fallback seed');
    }
    // The literal module is traced into the Vercel function bundle. No
    // filesystem wildcard/runtime cloud credential is needed during outages.
    await writeFile(seedFile,
      '// Verified public offsite seed; generated by ops/capture-standby.mjs.\n' +
      'export default Object.freeze(' + JSON.stringify(ready, null, 2) + ');\n',
      {encoding:'utf8', mode:0o600});
  }
  const report = {approved:expected, written:Object.keys(ready).length,
    skipped:failed.sort()};
  console.log('SNAPSHOT_SUMMARY ' + JSON.stringify(report));
  return report;
}
// A PR requires every approved source; production refresh keeps valid assets on partial failures.
export const captureExitCode = (report, {requireAll = false} = {}) =>
  !report || report.written < 1 ||
    (requireAll && (report.written !== report.approved ||
      report.skipped?.length > 0)) ? 1 : 0;
if (process.argv[1] && import.meta.url === new URL('file://' + resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  const dirFlag = args.indexOf('--out-dir');
  const seedFlag = args.indexOf('--seed-file');
  if (dirFlag < 0 || !args[dirFlag + 1]) {
    console.error('Usage: capture-standby.mjs --out-dir DIR [--seed-file FILE] [--require-all]');
    process.exitCode = 2;
  } else {
    captureAll({outDir:args[dirFlag + 1],
      seedFile:seedFlag >= 0 ? args[seedFlag + 1] : null}).then(result => {
      const requireAll = args.includes('--require-all');
      if (captureExitCode(result, {requireAll}) !== 0) {
        console.error('SNAPSHOT_CAPTURE_INCOMPLETE ' +
          JSON.stringify({...result, requireAll}));
        process.exitCode = 1;
      }
      if (result.skipped.length && process.env.GITHUB_ACTIONS) {
        console.warn('::warning::Partial offsite snapshot refresh: ' +
          result.skipped.join(', '));
      }
    }).catch(error => {
      console.error('SNAPSHOT_CAPTURE_FAILED ' + String(error?.message || error));
      process.exitCode = 1;
    });
  }
}
